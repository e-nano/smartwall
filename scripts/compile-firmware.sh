#!/usr/bin/env bash
set -Eeuo pipefail

project_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
version_file="$project_dir/.firmware-version"
version_header="$project_dir/include/FirmwareVersion.generated.h"
build_output="$project_dir/.pio/build/smartbin_integrated_rev02/firmware.bin"
inbox_dir="$project_dir/platform/firmware/integrated"
current_version="$(tr -d '[:space:]' < "$version_file")"

if [[ ! "$current_version" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
  echo "Invalid version in $version_file: $current_version" >&2
  exit 1
fi

if [[ $# -gt 1 ]]; then
  echo "Usage: $0 [next-semantic-version]" >&2
  exit 1
fi

if [[ $# -eq 1 ]]; then
  next_version="$1"
else
  IFS=. read -r current_major current_minor current_patch <<< "$current_version"
  next_version="$current_major.$current_minor.$((current_patch + 1))"
fi

if [[ ! "$next_version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][A-Za-z0-9.-]+)?$ ]]; then
  echo "Invalid semantic version: $next_version" >&2
  exit 1
fi
if [[ "$next_version" == "$current_version" ]] ||    [[ "$(printf '%s\n%s\n' "$current_version" "$next_version" | sort -V | tail -n 1)" != "$next_version" ]]; then
  echo "Next version must be greater than $current_version" >&2
  exit 1
fi
if [[ -e "$inbox_dir/smartwall-$next_version.bin" ]]; then
  echo "Release smartwall-$next_version.bin already exists in the backend inbox" >&2
  exit 1
fi

if command -v pio >/dev/null 2>&1; then
  pio_bin="$(command -v pio)"
elif [[ -x "$HOME/.platformio/penv/bin/pio" ]]; then
  pio_bin="$HOME/.platformio/penv/bin/pio"
else
  echo "PlatformIO CLI was not found" >&2
  exit 1
fi

backup_header="$(mktemp)"
cp "$version_header" "$backup_header"
release_temp=""
cleanup() {
  status=$?
  if [[ $status -ne 0 ]]; then
    cp "$backup_header" "$version_header"
    [[ -z "$release_temp" ]] || rm -f "$release_temp"
    echo "Build failed; firmware version remains $current_version" >&2
  fi
  rm -f "$backup_header"
  exit "$status"
}
trap cleanup EXIT

printf '#pragma once\n\n// Generated by scripts/compile-firmware.sh. Do not edit by hand.\n#define SMARTWALL_FIRMWARE_VERSION "%s"\n' \
  "$next_version" > "$version_header"

echo "Building SmartWall firmware $next_version..."
"$pio_bin" run --project-dir "$project_dir" --environment smartbin_integrated_rev02

if [[ ! -s "$build_output" ]]; then
  echo "PlatformIO did not produce $build_output" >&2
  exit 1
fi

mkdir -p "$inbox_dir"
release_temp="$inbox_dir/.smartwall-$next_version.bin.$$"
install -m 0644 "$build_output" "$release_temp"
mv "$release_temp" "$inbox_dir/smartwall-$next_version.bin"
release_temp=""
printf '%s\n' "$next_version" > "$version_file"

trap - EXIT
rm -f "$backup_header"
echo "Firmware $next_version is ready in $inbox_dir"
echo "Build only: publish a signed release separately before deployment."
